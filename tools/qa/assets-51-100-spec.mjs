function plannedPathsFor(number, stem, hasFirstPersonRepresentation = false) {
  const id = String(number).padStart(3, '0');
  const fileStem = `asset_${id}_${stem}`;
  const sheet = `sheet_${String(Math.ceil(number / 10)).padStart(2, '0')}`;
  const paths = {
    source: `asset_sources/blender/assets_51_100/${sheet}/${fileStem}.blend`,
    canonicalGlb: `Assets/assets_51_100/glb/${sheet}/${fileStem}.glb`,
    runtimeGlb: `vendor/models/assets_51_100/${sheet}/${fileStem}.glb`,
    runtimeIntegrationFile: `src/render3d/assets51to100/${fileStem}.js`,
  };
  if (hasFirstPersonRepresentation) {
    const firstPersonStem = `${fileStem}_fp`;
    paths.firstPersonSource = `asset_sources/blender/assets_51_100/firstperson/${firstPersonStem}.blend`;
    paths.firstPersonCanonicalGlb = `Assets/assets_51_100/glb/firstperson/${firstPersonStem}.glb`;
    paths.firstPersonRuntimeGlb = `vendor/models/assets_51_100/firstperson/${firstPersonStem}.glb`;
  }
  return Object.freeze(paths);
}

function freezeCandidates(value = {}) {
  const normalized = { ...emptyCandidates(), ...value };
  return Object.freeze(Object.fromEntries(Object.entries(normalized).map(([key, paths]) => [key, Object.freeze([...paths])])));
}

